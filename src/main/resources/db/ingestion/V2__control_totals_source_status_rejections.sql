CREATE TABLE downstream_rejection (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        VARCHAR(100) NOT NULL,
    batch_id         VARCHAR(64)  NOT NULL,
    source_id        VARCHAR(100) NOT NULL,
    record_reference VARCHAR(200) NOT NULL,
    error_code       VARCHAR(60)  NOT NULL,
    reason           TEXT         NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_downstream_rejection UNIQUE (tenant_id, batch_id, record_reference)
);
CREATE INDEX idx_downstream_rejection_batch ON downstream_rejection (tenant_id, batch_id);

