CREATE TABLE source_config (
    tenant_id        VARCHAR(100) NOT NULL,
    source_id        VARCHAR(100) NOT NULL,
    version          INT          NOT NULL,
    rail             VARCHAR(30)  NOT NULL,
    connection_type  VARCHAR(30)  NOT NULL,
    required_columns TEXT         NOT NULL,
    numeric_columns  TEXT         NOT NULL DEFAULT '',
    created_by       VARCHAR(100) NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    PRIMARY KEY (tenant_id, source_id, version)
);

CREATE TABLE ingestion_batch (
    batch_id       VARCHAR(64) PRIMARY KEY,
    tenant_id      VARCHAR(100) NOT NULL,
    source_id      VARCHAR(100) NOT NULL,
    source_version INT          NOT NULL,
    feed_id        VARCHAR(200) NOT NULL,
    file_checksum  VARCHAR(64)  NOT NULL,
    vault_location VARCHAR(500) NOT NULL,
    status         VARCHAR(40)  NOT NULL,
    declared_count BIGINT,
    received       BIGINT       NOT NULL DEFAULT 0,
    accepted       BIGINT       NOT NULL DEFAULT 0,
    quarantined    BIGINT       NOT NULL DEFAULT 0,
    duplicates     BIGINT       NOT NULL DEFAULT 0,
    status_detail  VARCHAR(1000),
    created_by     VARCHAR(100) NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    completed_at   TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_batch_feed UNIQUE (tenant_id, source_id, feed_id, file_checksum)
);
CREATE INDEX idx_batch_tenant ON ingestion_batch (tenant_id, created_at DESC);

CREATE TABLE quarantine_entry (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id         VARCHAR(64)  NOT NULL REFERENCES ingestion_batch (batch_id),
    tenant_id        VARCHAR(100) NOT NULL,
    record_reference VARCHAR(200) NOT NULL,
    reasons          TEXT         NOT NULL,
    raw_line         TEXT,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE INDEX idx_quarantine_batch ON quarantine_entry (batch_id);

CREATE TABLE ingested_record (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    VARCHAR(100) NOT NULL,
    source_id    VARCHAR(100) NOT NULL,
    content_hash VARCHAR(64)  NOT NULL,
    batch_id     VARCHAR(64)  NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE INDEX idx_ingested_hash ON ingested_record (tenant_id, source_id, content_hash, created_at);
