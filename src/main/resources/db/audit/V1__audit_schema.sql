CREATE TABLE audit_event (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       VARCHAR(100) NOT NULL,
    seq_no          BIGINT       NOT NULL,
    fingerprint     VARCHAR(64)  NOT NULL,
    actor           VARCHAR(100) NOT NULL,
    action          VARCHAR(100) NOT NULL,
    entity_type     VARCHAR(100) NOT NULL,
    entity_id       VARCHAR(200) NOT NULL,
    before_json     TEXT,
    after_json      TEXT,
    correlation_id  VARCHAR(100),
    source_service  VARCHAR(100),
    at_utc          TIMESTAMP WITH TIME ZONE NOT NULL,
    previous_hash   VARCHAR(64)  NOT NULL,
    event_hash      VARCHAR(64)  NOT NULL,
    CONSTRAINT uq_audit_seq UNIQUE (tenant_id, seq_no),
    -- consumers are at-least-once; an identical message is stored once
    CONSTRAINT uq_audit_fingerprint UNIQUE (tenant_id, fingerprint)
);
CREATE INDEX idx_audit_entity ON audit_event (tenant_id, entity_type, entity_id, seq_no);
CREATE INDEX idx_audit_actor ON audit_event (tenant_id, actor, at_utc);
CREATE INDEX idx_audit_time ON audit_event (tenant_id, at_utc);

CREATE TABLE audit_chain_head (
    tenant_id VARCHAR(100) PRIMARY KEY,
    last_seq  BIGINT      NOT NULL,
    last_hash VARCHAR(64) NOT NULL
);

-- Append-only at the storage layer: even the application role cannot rewrite history.
CREATE FUNCTION audit_event_immutable() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'audit_event is append-only (% is not permitted)', TG_OP;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_audit_event_immutable
    BEFORE UPDATE OR DELETE ON audit_event
    FOR EACH ROW EXECUTE FUNCTION audit_event_immutable();
