CREATE TABLE closure_period (
    period_id        VARCHAR(64)  PRIMARY KEY,
    tenant_id        VARCHAR(100) NOT NULL,
    rail             VARCHAR(30)  NOT NULL,
    period_key       VARCHAR(50)  NOT NULL,
    from_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    to_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    state            VARCHAR(30)  NOT NULL,
    materiality_minor BIGINT      NOT NULL DEFAULT 0 CHECK (materiality_minor >= 0),
    created_by       VARCHAR(100) NOT NULL,
    submitted_by     VARCHAR(100),
    first_approver   VARCHAR(100),
    second_approver  VARCHAR(100),
    closed_at        TIMESTAMP WITH TIME ZONE,
    snapshot_id      VARCHAR(80),
    version          BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_period UNIQUE (tenant_id, rail, period_key),
    CONSTRAINT ck_period_range CHECK (to_at > from_at)
);
CREATE INDEX idx_period_lock ON closure_period (tenant_id, rail, from_at, to_at) WHERE state = 'CLOSED';

CREATE TABLE closure_check (
    period_id    VARCHAR(64)  NOT NULL REFERENCES closure_period (period_id),
    check_name   VARCHAR(60)  NOT NULL,
    passed       BOOLEAN      NOT NULL,
    detail       TEXT         NOT NULL,
    evaluated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (period_id, check_name)
);

CREATE TABLE carry_forward (
    period_id    VARCHAR(64)  NOT NULL REFERENCES closure_period (period_id),
    case_id      VARCHAR(64)  NOT NULL,
    rationale    TEXT         NOT NULL,
    amount_minor BIGINT       NOT NULL,
    created_by   VARCHAR(100) NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    PRIMARY KEY (period_id, case_id)
);

CREATE TABLE closure_history (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_id  VARCHAR(64)  NOT NULL REFERENCES closure_period (period_id),
    from_state VARCHAR(30),
    to_state   VARCHAR(30)  NOT NULL,
    actor      VARCHAR(100) NOT NULL,
    reason     TEXT,
    at_utc     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE INDEX idx_closure_history ON closure_history (period_id, id);
