CREATE TABLE reconciliation_case (
    case_id            VARCHAR(64)  PRIMARY KEY,
    tenant_id          VARCHAR(100) NOT NULL,
    break_id           VARCHAR(100) NOT NULL,
    rail               VARCHAR(30)  NOT NULL,
    match_key          VARCHAR(200) NOT NULL,
    reason_code        VARCHAR(30)  NOT NULL,
    detail_code        VARCHAR(100),
    explanation        TEXT,
    state              VARCHAR(30)  NOT NULL,
    financial_impact_minor BIGINT   NOT NULL,
    currency           CHAR(3)      NOT NULL,
    transaction_time   TIMESTAMP WITH TIME ZONE NOT NULL,
    detected_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    deadline_at        TIMESTAMP WITH TIME ZONE,
    assigned_owner     VARCHAR(100),
    involved_transactions TEXT      NOT NULL,
    closure_reason     VARCHAR(100),
    alert_70_sent      BOOLEAN      NOT NULL DEFAULT FALSE,
    alert_90_sent      BOOLEAN      NOT NULL DEFAULT FALSE,
    version            BIGINT       NOT NULL DEFAULT 0,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_case_break UNIQUE (tenant_id, break_id)
);
CREATE INDEX idx_case_queue ON reconciliation_case (tenant_id, state, detected_at DESC, case_id);
CREATE INDEX idx_case_deadline ON reconciliation_case (tenant_id, deadline_at) WHERE state <> 'CLOSED';

CREATE TABLE case_history (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id  VARCHAR(64)  NOT NULL REFERENCES reconciliation_case (case_id),
    state    VARCHAR(30)  NOT NULL,
    at_utc   TIMESTAMP WITH TIME ZONE NOT NULL,
    actor    VARCHAR(100) NOT NULL,
    reason   TEXT
);
CREATE INDEX idx_history_case ON case_history (case_id, id);

CREATE TABLE case_comment (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id  VARCHAR(64)  NOT NULL REFERENCES reconciliation_case (case_id),
    tenant_id VARCHAR(100) NOT NULL,
    author   VARCHAR(100) NOT NULL,
    body     TEXT         NOT NULL,
    at_utc   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE INDEX idx_comment_case ON case_comment (case_id, id);

-- RBI Turn-Around-Time clocks as configuration data (HLD 10.2). tenant '*' = platform default.
CREATE TABLE tat_rail_clock (
    tenant_id            VARCHAR(100) NOT NULL,
    rail                 VARCHAR(30)  NOT NULL,
    deadline_days        INT          NOT NULL CHECK (deadline_days >= 0),
    use_working_days     BOOLEAN      NOT NULL DEFAULT FALSE,
    compensation_per_day_minor BIGINT NOT NULL CHECK (compensation_per_day_minor >= 0),
    PRIMARY KEY (tenant_id, rail)
);
